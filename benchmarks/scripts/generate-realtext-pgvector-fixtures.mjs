#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const sourceRoot = path.resolve(process.env.REALTEXT_SOURCE_ROOT || process.cwd());
const fixtureRows = Number(process.env.REALTEXT_ROWS || 100000);
const fixtureKbId = Number(process.env.REALTEXT_KB_ID || 92001);
const fixtureTenantId = Number(process.env.REALTEXT_TENANT_ID || 92001);
const fixtureUserId = Number(process.env.REALTEXT_USER_ID || 92001);
const fixtureDocId = Number(process.env.REALTEXT_DOC_ID || 92001);
const chunkChars = Number(process.env.REALTEXT_CHUNK_CHARS || 900);
const overlapChars = Number(process.env.REALTEXT_OVERLAP_CHARS || 120);
const maxFileBytes = Number(process.env.REALTEXT_MAX_FILE_BYTES || 524288);
const topicVectors = Number(process.env.REALTEXT_TOPIC_VECTORS || 64);

const allowedExtensions = new Set([
  '.md', '.java', '.sql', '.yml', '.yaml', '.xml', '.properties', '.txt', '.ts', '.tsx', '.js', '.mjs'
]);
const ignoredDirs = new Set([
  '.git', '.idea', '.gradle', '.mvn', 'node_modules', 'target', 'dist', 'build', '.next', 'coverage', 'raw-results'
]);
const ignoredFileNames = new Set(['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock']);

function sqlComment(text) {
  return String(text).replace(/\*\//g, '* /');
}

function copyEscape(value) {
  return String(value)
    .replace(/\\/g, '\\\\')
    .replace(/\t/g, '\\t')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r');
}

function normalizeText(text) {
  return text
    .replace(/\u0000/g, '')
    .replace(/[ \t]+/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function shouldUseFile(filePath) {
  const name = path.basename(filePath);
  if (ignoredFileNames.has(name)) return false;
  const ext = path.extname(filePath).toLowerCase();
  if (!allowedExtensions.has(ext)) return false;
  const stat = fs.statSync(filePath);
  return stat.isFile() && stat.size > 80 && stat.size <= maxFileBytes;
}

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ignoredDirs.has(entry.name)) continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(fullPath, out);
    } else if (entry.isFile() && shouldUseFile(fullPath)) {
      out.push(fullPath);
    }
  }
  return out;
}

function splitIntoChunks(text) {
  const normalized = normalizeText(text);
  if (normalized.length <= chunkChars) return normalized.length >= 80 ? [normalized] : [];

  const chunks = [];
  let start = 0;
  const step = Math.max(1, chunkChars - overlapChars);
  while (start < normalized.length) {
    let end = Math.min(normalized.length, start + chunkChars);
    if (end < normalized.length) {
      const breakAt = Math.max(
        normalized.lastIndexOf('\n\n', end),
        normalized.lastIndexOf('. ', end),
        normalized.lastIndexOf('。', end),
        normalized.lastIndexOf(';', end)
      );
      if (breakAt > start + Math.floor(chunkChars * 0.55)) {
        end = breakAt + 1;
      }
    }
    const chunk = normalized.slice(start, end).trim();
    if (chunk.length >= 80) chunks.push(chunk);
    if (end >= normalized.length) break;
    start += step;
  }
  return chunks;
}

const files = walk(sourceRoot).sort();
const sourceChunks = [];
for (const file of files) {
  let text;
  try {
    text = fs.readFileSync(file, 'utf8');
  } catch {
    continue;
  }
  const relativePath = path.relative(sourceRoot, file) || path.basename(file);
  for (const chunk of splitIntoChunks(text)) {
    sourceChunks.push({ sourcePath: relativePath, text: chunk });
  }
}

if (sourceChunks.length === 0) {
  console.error(`No source chunks found under ${sourceRoot}`);
  process.exit(2);
}

